import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = fileURLToPath(new URL('../', import.meta.url));
const out = resolve(root, 'src/lib/stream/processing/wgsl');
const scratch = mkdtempSync(resolve(tmpdir(), 'holyarrs-shaders-'));
const target = process.argv[2];
if (!target) throw new Error('Pass the path to a Naga CLI executable or WASI launcher.');
const naga = resolve(target);
const vertex = 'compute_main';
const only = process.argv[3];
const server = await createServer({ root, configFile: false, server: { middlewareMode: true, ws: false }, appType: 'custom' });
const base = '/src/lib/stream/processing';
const { effectFragment } = await server.ssrLoadModule(base + '/glsl-effects.ts');
const { shaderPasses } = await server.ssrLoadModule(base + '/mpv-shaders.ts');
const { smaaFragments } = await server.ssrLoadModule(base + '/smaa-shaders.ts');
const { stages, filterOrder } = await server.ssrLoadModule(base + '/presets.ts');
mkdirSync(out, { recursive: true });

function computeSource(fragment) {
	const textures = [...fragment.matchAll(/^uniform sampler2D (\w+);$/gm)];
	const names = textures.map(([, name]) => name);
	let source = fragment
		.replace(/^#version.*$/m, '')
		.replace(/^uniform sampler2D .*$/gm, '')
		.replace(/^precision .*$/gm, '')
		.replace(/^uniform (vec2|float|vec4) (sourceSize|outputSize|params|reference|frameTime);$/gm, '')
		.replace(/^in vec2 uv;$/m, '')
		.replace(/^out vec4 result;$/m, '')
		.replace(/\bgl_FragCoord\b/g, 'pixelPosition')
		.replace(/\bvoid main\s*\(/, 'void effectMain(')
		.replace(/\bdiscard\s*;/g, '{ result = vec4(0.0); return; }');
	source = source.replace(/\btexture\(/g, 'textureLod(');
	let pos = 0;
	while ((pos = source.indexOf('textureLod(', pos)) !== -1) {
		pos += 'textureLod('.length;
		let depth = 1, end = pos;
		while (depth && end < source.length) {
			const char = source[end++];
			if (char === '(') depth++;
			if (char === ')') depth--;
		}
		source = source.slice(0, end - 1) + ',0.0' + source.slice(end - 1);
	}
	for (const name of names) {
		source = source.replace(new RegExp(`\\b(textureLod|textureSize|texelFetch)\\(${name},`, 'g'), `$1(sampler2D(${name},videoSampler),`);
	}
	const inputs = names.map((name, index) => `layout(set=0,binding=${index + 1}) uniform texture2D ${name};`).join('\n');
	return `#version 450
layout(local_size_x=8,local_size_y=8) in;
layout(set=0,binding=0) uniform sampler videoSampler;
${inputs}
layout(set=0,binding=7,rgba16f) writeonly uniform image2D destination;
layout(std140,set=0,binding=6) uniform Uniforms { vec4 params; vec2 sourceSize; vec2 outputSize; float reference; float frameTime; };
vec2 uv;
vec4 result;
vec4 pixelPosition;
${source}
void main() {
	ivec2 position=ivec2(gl_GlobalInvocationID.xy);
	if (any(greaterThanEqual(position,ivec2(outputSize)))) return;
	pixelPosition=vec4(vec2(position)+0.5,0.0,1.0);
	uv=pixelPosition.xy/outputSize;
	effectMain();
	imageStore(destination,position,result);
}`;
}

function translate(key, fragment) {
	if (only && !key.startsWith(only)) return;
	const name = key.replace(':', '-');
	const source = resolve(scratch, name + '.comp');
	const binary = resolve(scratch, name + '.spv');
	const generated = resolve(scratch, name + '.wgsl');
	writeFileSync(source, computeSource(fragment));
	execFileSync('glslangValidator', ['-V', '-o', binary, source], { stdio: ['ignore', 'inherit', 'inherit'] });
	const compiler = naga.endsWith('.mjs') ? [process.execPath, [naga]] : [naga, []];
	execFileSync(compiler[0], [...compiler[1], basename(binary), basename(generated)], { cwd: scratch, stdio: ['ignore', 'inherit', 'inherit'] });
	const shader = readFileSync(generated, 'utf8').replace('@workgroup_size(8, 8, 1)', '@workgroup_size(GROUP_X, GROUP_Y, 1)').replace(/\bfn main\(/, `fn ${vertex}(`).replace(/[ \t]+$/gm, '');
	writeFileSync(resolve(out, name + '.wgsl'), '// Generated by scripts/generate-processing-shaders.mjs.\n' + shader);
}

try {
	for (const stage of [...Object.keys(stages), ...filterOrder, 'present', 'luma_input', 'luma_output']) {
		const passes = await shaderPasses(stage);
		if (passes) passes.forEach((pass, i) => translate(`${stage}:${i}`, pass.fragment));
		else if (stage !== 'smaa') translate(stage, effectFragment(stage));
	}
	smaaFragments.forEach((fragment, i) => translate(`smaa:${i}`, fragment));
} finally { await server.close(); }
